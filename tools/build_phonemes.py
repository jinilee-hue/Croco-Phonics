"""Expected phonemes for the phonics-api word check -> js/phonemes.js (window.CROCO_PH = {word: [ARPABET]}): every level
word of js/words.js, from the company phonics-api's own G2P (phonics-kit/tools/papi.py g2p, cached). Re-run after
build_words.py. A plain script file, so file:// keeps working.
usage: python3 tools/build_phonemes.py      (key: ~/.config/phonics-api/key — never printed)
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(pathlib.Path.home() / 'Documents/Jini/2026/Phonics/phonics-kit/tools'))
import papi  # noqa: E402

wj = json.loads((ROOT / 'js' / 'words.js').read_text(encoding='utf-8').split('=', 1)[1].rstrip().rstrip(';'))
words = sorted({w['w'] for lv in wj['levels'] for w in lv['words']})
table = papi.g2p(words, log=lambda *a: None)
(ROOT / 'js' / 'phonemes.js').write_text('/* generated by tools/build_phonemes.py — do not edit */\nwindow.CROCO_PH = '
                                         + json.dumps(dict(sorted(table.items())), separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{len(table)} words -> js/phonemes.js')
