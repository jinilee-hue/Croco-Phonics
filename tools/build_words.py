"""Build js/words.js — the crocodile-teeth words: every m-word of FPR K Unit 1 · Lesson 1 (pages 9-20).

User rule: "m 단어들은 다 fpr k unit1 lesson1에 교재에 나오는걸로 해야해" → only words that appear on the Lesson 1 pages.
Source: SAD·FPR 단어 연구 자료집 → ~/dev/sadfpr-studio/data/b2_book_FPRK.json
  lp: lesson → [first page, last page]; rows: lemma + page + lesson; words: lemma → printed / picture pages.
Picture cards: the same FPR K picture art Magic Block (Phonics-Jenga) uses → copied to assets/cards/<word>.webp.
Only words, Korean glosses and page numbers are written — no textbook sentences (internal material).

Run: python3 tools/build_words.py
"""
import json
import os
import pathlib
import shutil

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = pathlib.Path(os.path.expanduser('~/dev/sadfpr-studio/data/b2_book_FPRK.json'))
JENGA = pathlib.Path(os.path.expanduser('~/Documents/Jini/2026/Phonics/Phonics-Jenga/public/cards'))
B = json.loads(SRC.read_text(encoding='utf-8'))
W, GM = B['words'], B['gm']
LESSON = 1
P0, P1 = B['lp'][str(LESSON)]
assert {int(k): v for k, v in B['lu'].items()}[LESSON] == 1, 'Lesson 1 must be in Unit 1'
names = {n.lower() for n in B['names']}

# every m-lemma with a row on a Lesson 1 page
rows = {}
for r in B['rows']:
    if r.get('lesson') == LESSON and r['lemma'][:1].lower() == 'm' and r['lemma'].lower() not in names:
        rows.setdefault(r['lemma'], set()).add(r.get('page'))

# not a picture word: "my" is printed only (p11) — a card game needs a picture to show
EXCLUDED = {'my': '그림 없는 기능어(교재 p11 글자로만 나옴) — 그림카드로 보여줄 수 없음'}

words = []
for lemma in sorted(rows):
    if lemma in EXCLUDED:
        continue
    v = W[lemma]
    l1 = sorted({p for k in ('printed', 'picture') for p in v.get(k, []) if P0 <= p <= P1})
    assert l1, lemma
    card = JENGA / f'{lemma}.webp'
    assert card.exists(), f'no picture card for {lemma}'
    dst = ROOT / 'assets' / 'cards' / f'{lemma}.webp'
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(card, dst)
    ko = GM.get(lemma, ['', ''])[0]
    words.append({'w': lemma, 'ko': ko, 'pages': l1, 'cat': v.get('cat', ''), 'card': f'assets/cards/{lemma}.webp'})

assert set(rows) == {w['w'] for w in words} | set(EXCLUDED), 'every Lesson 1 m-word is a tooth word or excluded'
out = {
    'book': 'FPR K (From Phonics to Reading K) · Unit 1 · Lesson 1',
    'pages': [P0, P1],
    'sound': 'm',
    'source': 'SAD·FPR 단어 연구 자료집 · b2_book_FPRK.json',
    'excluded': EXCLUDED,
    'words': words,
}
js = ROOT / 'js' / 'words.js'
js.write_text('/* generated by tools/build_words.py — do not edit */\nwindow.CROCO_WORDS = '
              + json.dumps(out, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
for w in words:
    print(f"{w['w']:9s} {w['ko'][:10]:10s} p{w['pages']}  {w['cat']}")
print(len(words), 'words (excluded:', ', '.join(EXCLUDED), ') →', js)
