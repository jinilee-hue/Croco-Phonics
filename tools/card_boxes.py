#!/usr/bin/env python3
"""Each card picture's drawn area (alpha bbox) → js/card-boxes.js, so a card can size the DRAWING (not the 512×539
canvas) to its picture box: the top (trap) card showed pictures at very different sizes (user: "상단 카드에 이미지 크기
제각각 인거 같은데 크기 통일되게 맞춰줘") — a wide drawing (map) filled a third of the height a tall one (man) did, and some
drawings sit small inside their canvas. Run again after the cards change:

  uv run --with pillow --with numpy python tools/card_boxes.py
"""
import json, pathlib
import numpy as np
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent
boxes = {}
for f in sorted((ROOT / 'assets/cards').glob('*.webp')):
    a = np.asarray(Image.open(f).convert('RGBA'))[..., 3]
    H, W = a.shape
    ys, xs = np.nonzero(a > 96)                      # the drawing, not its faint soft shadow
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    boxes[f.stem] = [round(x0 / W, 4), round(y0 / H, 4), round((x1 - x0) / W, 4), round((y1 - y0) / H, 4)]
out = ROOT / 'js/card-boxes.js'
out.write_text('/* generated by tools/card_boxes.py: each card picture\'s drawn area [x, y, w, h] as fractions of its canvas */\n'
               'window.CROCO_CARD_BOX = ' + json.dumps(boxes, separators=(',', ':')) + ';\n')
hs = sorted((v[3], k) for k, v in boxes.items())
print(len(boxes), 'cards →', out.name, '| drawn height: min', hs[0], 'max', hs[-1])
