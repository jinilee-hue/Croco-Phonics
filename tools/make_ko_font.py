"""Korean font for EN | 한 (game.js applyLang): Jua (Google Fonts, SIL OFL 1.1 — rounded, child-friendly, goes with
Baloo; the same font Magic Block uses), cut down to the Hangul the game shows, embedded as a data URL in css/font-ko.css
so index.html opened from disk (file://) still has it. The text is collected from js/game.js (bubbles, screen words),
tools/build_voice.py (Korean lines) and js/voice.js (Korean lines reused from Magic Block). Re-run after changing them.

    uv run --with fonttools --with brotli python tools/make_ko_font.py
"""
import base64
import pathlib
import re
import subprocess
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC_URL = 'https://github.com/google/fonts/raw/main/ofl/jua/Jua-Regular.ttf'
CACHE = pathlib.Path.home() / '.cache' / 'phonics-jenga' / 'fonts' / 'Jua-Regular.ttf'      # shared with Magic Block
OUT = ROOT / 'css' / 'font-ko.css'
SOURCES = [ROOT / 'js' / 'game.js', ROOT / 'tools' / 'build_voice.py', ROOT / 'js' / 'voice.js']

if not CACHE.exists():
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    urllib.request.urlretrieve(SRC_URL, CACHE)
HANGUL = r'[\u1100-\u11ff\u3130-\u318f\uac00-\ud7a3]'
chars = sorted({c for p in SOURCES if p.exists() for c in re.findall(HANGUL, p.read_text(encoding='utf-8'))})
if not chars:
    sys.exit('no Korean text found')
with tempfile.TemporaryDirectory() as d:
    woff = pathlib.Path(d) / 'jua.woff2'
    subprocess.run([sys.executable, '-m', 'fontTools.subset', str(CACHE), f'--unicodes={",".join(f"U+{ord(c):04X}" for c in chars)}',
                    '--flavor=woff2', f'--output-file={woff}', '--layout-features=*', '--no-hinting'], check=True)
    data = base64.b64encode(woff.read_bytes()).decode()
OUT.write_text('/* generated by tools/make_ko_font.py — Jua (SIL OFL 1.1), Hangul subset; Latin stays Baloo 2 */\n'
               "@font-face { font-family: 'Jua'; font-style: normal; font-weight: 400 900; font-display: block;\n"
               '  unicode-range: U+1100-11FF, U+3130-318F, U+AC00-D7A3;\n'
               f"  src: url(data:font/woff2;base64,{data}) format('woff2'); }}\n", encoding='utf-8')
print(f'{len(chars)} syllables → {OUT.relative_to(ROOT)} ({OUT.stat().st_size / 1024:.1f} KB)')
